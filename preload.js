const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('glass', {
  openFiles: () => ipcRenderer.invoke('open-files'),
  openFolder: () => ipcRenderer.invoke('open-folder'),
  resolveDropped: (files) => ipcRenderer.invoke('resolve-paths', Array.from(files, (f) => webUtils.getPathForFile(f))),
  resolvePaths: (paths) => ipcRenderer.invoke('resolve-paths', paths),
  metaBatch: (paths) => ipcRenderer.invoke('meta-batch', paths),
  cover: (p) => ipcRenderer.invoke('cover', p),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  pickWallpaper: (oldUrl) => ipcRenderer.invoke('pick-wallpaper', oldUrl),
  rename: (p, base) => ipcRenderer.invoke('rename', p, base),
  writeTags: (p, tags) => ipcRenderer.invoke('write-tags', p, tags),
  reveal: (p) => ipcRenderer.invoke('reveal', p),
  lookup: (q) => ipcRenderer.invoke('lookup', q),
  fetchArt: (url) => ipcRenderer.invoke('fetch-art', url),
  collage: (urls) => ipcRenderer.invoke('collage', urls),
  pickImageData: () => ipcRenderer.invoke('pick-image-data'),
  imageData: (url) => ipcRenderer.invoke('image-data', url),
  saveArtData: (dataUrl) => ipcRenderer.invoke('save-art-data', dataUrl),
  artHashes: (urls) => ipcRenderer.invoke('art-hashes', urls),
  artistInfo: (name) => ipcRenderer.invoke('artist-info', name),
  acts: {
    known: () => ipcRenderer.invoke('acts-known'),
    check: (items) => ipcRenderer.invoke('acts-check', items),
    search: (q) => ipcRenderer.invoke('acts-search', q),
  },
  lyrics: {
    get: (p, hints, mode) => ipcRenderer.invoke('lyrics-get', p, hints, mode),
    search: (q) => ipcRenderer.invoke('lyrics-search', q),
    pick: (p, r) => ipcRenderer.invoke('lyrics-pick', p, r),
    saveFile: (p, r) => ipcRenderer.invoke('lyrics-save-file', p, r),
  },
  storeGet: () => ipcRenderer.invoke('store-get'),
  storeSet: (data) => ipcRenderer.invoke('store-set', data),
  storeSetSync: (data) => ipcRenderer.sendSync('store-set-sync', data),
  win: (action) => ipcRenderer.send('win', action),
  zoom: {
    step: (dir) => ipcRenderer.send('zoom-step', dir),
    set: (f) => ipcRenderer.send('zoom-set', f),
    onChange: (cb) => ipcRenderer.on('zoom', (_e, f) => cb(f)),
  },
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  system: {
    transparency: () => ipcRenderer.invoke('sys:transparency'),
    openColors: () => ipcRenderer.invoke('sys:open-colors'),
  },
  // taskbar preview buttons: Glass reports play state, the buttons report clicks
  media: {
    state: (s) => ipcRenderer.send('thumbar', s),
    onAction: (cb) => ipcRenderer.on('media-action', (_e, a) => cb(a)),
  },
  onOpenPaths: (cb) => ipcRenderer.on('open-paths', (_e, tracks) => cb(tracks)),
  onMaximized: (cb) => ipcRenderer.on('maximized', (_e, v) => cb(v)),
  scan: {
    start: () => ipcRenderer.invoke('scan:start'),
    stop: () => ipcRenderer.invoke('scan:stop'),
    add: (paths, skipped) => ipcRenderer.invoke('scan:add', paths, skipped),
    findFromSettings: () => ipcRenderer.invoke('scan:find'),
    status: () => ipcRenderer.invoke('scan:status'),
    onProgress: (cb) => ipcRenderer.on('scan:progress', (_e, m) => cb(m)),
  },
  localAccount: {
    state: () => ipcRenderer.invoke('localAccount:state'),
    create: (contact, password, username) => ipcRenderer.invoke('localAccount:create', contact, password, username),
    signIn: (contact, password) => ipcRenderer.invoke('localAccount:signIn', contact, password),
    signOut: () => ipcRenderer.invoke('localAccount:signOut'),
    remove: () => ipcRenderer.invoke('localAccount:remove'),
    googleAvailable: () => ipcRenderer.invoke('localAccount:googleAvailable'),
    googleStart: () => ipcRenderer.invoke('localAccount:googleStart'),
    googleCancel: () => ipcRenderer.invoke('localAccount:googleCancel'),
    googleFinish: (username) => ipcRenderer.invoke('localAccount:googleFinish', username),
  },
  updates: {
    state: () => ipcRenderer.invoke('update:state'),
    check: () => ipcRenderer.invoke('update:check'),
    install: () => ipcRenderer.invoke('update:install'),
    open: () => ipcRenderer.invoke('update:open'),
    on: (cb) => ipcRenderer.on('update', (_e, s) => cb(s)),
  },
});
